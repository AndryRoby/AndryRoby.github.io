/** Index glyfu pre znak textu (veľké písmená = malé). Neznámy znak = medzera. */
export function glyfZnaku(ch) {
  const k = INDEX[String(ch).toLowerCase()];
  return k === undefined ? PRAZDNY : k;
}

export function body(g) {
  const o = [];
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if ((g[y] >> (4 - x)) & 1) o.push(y * 5 + x);
  return o;
}

export function vzdialenost(a, b) {
  let d = 0;
  for (let y = 0; y < 7; y++) { let x = (a[y] ^ b[y]) & 31; while (x) { d += x & 1; x >>= 1; } }
  return d;
}

/** Najdlhší zvislý ťah glyfu (počet bodov nad sebou). */
export function zvislyTah(g) {
  let best = 0;
  for (let x = 0; x < 5; x++) {
    let run = 0;
    for (let y = 0; y < 7; y++) { run = (g[y] >> (4 - x)) & 1 ? run + 1 : 0; if (run > best) best = run; }
  }
  return best;
}

/** Šikmé spojenie: dva body po uhlopriečke bez spoločného suseda (to by bol šikmý ťah). */
export function maSikminu(g) {
  const at = (x, y) => (x < 0 || y < 0 || x > 4 || y > 6 ? 0 : (g[y] >> (4 - x)) & 1);
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) {
    if (!at(x, y)) continue;
    for (const dx of [1, -1]) if (at(x + dx, y + 1) && !at(x + dx, y) && !at(x, y + 1)) return true;
  }
  return false;
}
